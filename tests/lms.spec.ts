async function login(page:Page,role:"admin"|"guru"|"siswa"){
 await page.goto("/login");
 await page.getByLabel("Identitas akun").fill(role+"@e2e.invalid");
 await page.getByLabel("Kata sandi",{exact:true}).fill(password);
 await page.getByRole("button",{name:"Masuk",exact:true}).click();
 await expect(page).toHaveURL(role==="admin"?/\/dashboard$/:new RegExp("/dashboard/"+(role==="guru"?"teacher":"student")+"$"));
 await expect(page.getByText("Portal "+(role==="admin"?"Admin":role==="guru"?"Guru":"Siswa"),{exact:true})).toBeVisible();
}
async function logout(page:Page){await page.getByRole("button",{name:"Keluar",exact:true}).click();await expect(page).toHaveURL(/\/login$/);}
