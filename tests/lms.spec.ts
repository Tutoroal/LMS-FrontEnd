test("mobile menu, cross-role redirect and revoked logout token",async({page,request})=>{
 await page.setViewportSize({width:390,height:844});
 await login(page,"siswa");
 await page.getByRole("button",{name:"Buka navigasi"}).click();
 await page.getByRole("link",{name:"Kelas & Jadwal",exact:true}).click();
 await expect(page).toHaveURL(/\/student\/class$/);
 await expect(page.getByText("Pemrograman Web",{exact:true})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 await page.screenshot({path:"test-results/student-mobile.png",fullPage:true});
 await page.goto("/dashboard/users/admin");
 await expect(page).toHaveURL(/\/dashboard\/student$/);
 const token=await page.evaluate(()=>localStorage.getItem("token"));
 const denied=await request.get("http://localhost:18080/api/admin/users",{headers:{Authorization:"Bearer "+token}});
 expect(denied.status()).toBe(403);
 await page.getByRole("button",{name:"Buka navigasi"}).click();
 await logout(page);
 const revoked=await request.get("http://localhost:18080/api/auth/me",{headers:{Authorization:"Bearer "+token}});
 expect(revoked.status()).toBe(401);
});

